export type GuidedStageDefinition = {
  id: string;
  label: string;
  nextPreview?: string;
};

function plan(labels: string[]): GuidedStageDefinition[] {
  return labels.map((label, index) => ({
    id: label.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || `stage-${index + 1}`,
    label,
    nextPreview: labels[index + 1],
  }));
}

